r"""Builds src/data/WardrobeItems.inc, Player > Wardrobe > Apply Wardrobe
Item's list, from the SP item catalog dump tools/data/catalog_sp_items.json
(see tools/extract_catalog.py for how it is made).

    python tools/extract_wardrobe_items.py tools/data/catalog_sp_items.json src/data/WardrobeItems.inc

Every "CLOTHING" item is filed under its ci_category hash. The catalog
doesn't name those hashes; GROUPS comes from the RDR2-HashDatabase's
CatalogItemCategories.json (CI_CATEGORY_WARDROBE_*) and the items' own names
(CLOTHING_HL_PLAYER_HAT_010_9 -> Hats); a category that has no named item
(or none that says what it is) lands in "Unsorted" with its hash in the
sub-label so it can be identified in-game. Only items listed in
tools/data/wardrobe_labelled_keys.json (the ones with a game display name) are
kept; regenerate that file from Wardrobe > Dump Wardrobe Names. Output lines are
{ item hash, "Group", "Sub-label" or nullptr, "NAME" or nullptr }.
"""
import json, os, sys

LABELLED = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "wardrobe_labelled_keys.json")

GROUPS = {
    0x851EBBD3: "Hats", 0xCDFBBB30: "Boots", 0xC46CC879: "Outfits",
    0x7A0945B8: "Pants", 0x6F58734F: "Coats", 0x29A49A30: "Vests",
    0xEE36E737: "Boot Accessories", 0x290B0496: "Shirts", 0x9989398B: "Gloves",
    0x4C6BA84F: "Suspenders", 0x9258E25E: "Hair", 0xC8F18EFC: "Spats",
    0x6971A6CB: "Chaps", 0xE2522CFB: "Neckwear", 0x04D4C7F4: "Neckwear",
    0x0A4688FB: "Neckwear", 0x5813E4A1: "Neckwear", 0x0DC70C0E: "Beards",
    0xF83D06FF: "Bodies", 0xB2D451D7: "Bodies", 0x8B1AA3BD: "Bodies",
    0xD711FD93: "Belts", 0xC534C3B3: "Eyes", 0xF6485068: "Eyes", 0x1B7C2B66: "Neckwear",
    0x78FB8FDC: "Dresses and Aprons", 0x28C9B4C5: "Dresses and Aprons",
    0x21811425: "Dresses and Aprons", 0xAA25A557: "Dresses and Aprons", 0x3D9F76CD: "Gunbelts", 0x09252916: "Holsters",
    0xCD31B12C: "Off-Hand Holsters", 0xDCD17F1F: "Satchels",
    0x415F0998: "Bandoliers", 0x59E6EE9B: "Accessories",
    0xE0AAD1D8: "Masks", 0xE7602540: "Badges", 0x9C333D0A: "Teeth",
    0x8A6955D1: "Talismans", 0x69A50219: "Talismans", 0x28D20583: "Talismans",
    0xAB219849: "Talismans", 0x8CB31516: "Talismans", 0x83B02BC4: "Talismans",
}


def main():
    src, out = sys.argv[1], sys.argv[2]
    items = [i for i in json.load(open(src)) if i["type"] == "CLOTHING"]
    # Only items the game has a display name for (the honor-level variants and
    # the nameless hashes would show as bare hashes in the menu).
    labelled = {int(k, 16) for k in json.load(open(LABELLED))["keys"]}
    items = [i for i in items if i["key"] in labelled]
    rows = []
    for i in items:
        cat = int(i["category"], 16)
        group = GROUPS.get(cat, "Unsorted")
        sub = None if cat in GROUPS else "0x%08X" % cat
        name = None if i["name"].startswith("0x") else i["name"]
        rows.append((group, sub or "", i["key"], name))
    rows.sort(key=lambda r: (r[0], r[1], r[3] is None, r[3] or "", r[2]))
    lines = ["// Generated by tools/extract_wardrobe_items.py from %s;" % src,
             "// regenerate rather than edit. { item hash, \"Group\", sub-label or nullptr, internal name or nullptr }"]
    for group, sub, key, name in rows:
        lines.append('{ 0x%08X, "%s", %s, %s },' % (
            key, group, '"%s"' % sub if sub else "nullptr", '"%s"' % name if name else "nullptr"))
    open(out, "w", newline="").write("\r\n".join(lines) + "\r\n")
    print(len(rows), "items")


main()
